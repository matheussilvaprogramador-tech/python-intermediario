#29.  O Enigma da Esfinge:  A Esfinge faz uma conta matemática surpresa (ex: Quanto é 15 * 3?).
#  Se o usuário usar o  input()  para digitar "45", ele ganha o tesouro. Senão, ele perde 50 pontos de vida. 
resposta=input("Quanto e 15*3 ?:")
if resposta == "45":
    print("Parabens voce ganhou o tesouro")
else:
    print("resposta errada voce perdeu 50 pontos de vida")
